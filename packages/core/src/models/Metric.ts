/**
 * Canonical ownership vocabulary for metric visibility decisions.
 * Ordered from lowest to highest ownership precedence.
 */
export type MetricOwnershipLayer =
  | 'parser'
  | 'dialect'
  | 'user-plan'
  | 'runtime'
  | 'user-entry';

/**
 * Origin of a metric - where it was created and its current state.
 *
 * Source origins:
 * - 'parser': Created by the parser from source text
 * - 'compiler': Synthesized by a compiler strategy
 * - 'dialect': Synthesized by a dialect policy before runtime
 * - 'runtime': Generated during execution (e.g., elapsed time)
 * - 'user': Collected from user input (e.g., actual reps completed)
 *
 * Value states:
 * - 'collected': Value has been collected and populated
 * - 'hinted': Value is a hint or suggestion not strictly enforced
 * - 'tracked': Value is actively being tracked during execution
 * - 'analyzed': Value is derived from analysis
 * - 'analyzed-estimated': Value is derived from estimation
 * - 'execution': Generated by runtime execution
 * - 'user-plan': Planned override set by user before execution
 */
export type MetricAction = 'suppress';

export type MetricOrigin =
  | 'parser'
  | 'compiler'
  | 'dialect'
  | 'runtime'
  | 'user'
  | 'collected'
  | 'hinted'
  | 'tracked'
  | 'analyzed'
  | 'analyzed-estimated'
  | 'execution'
  | 'user-plan'
  | 'diagnostic';

export type Origin = MetricOrigin;

export interface IMetric {
  readonly image?: string;
  readonly value?: unknown;
  /**
   * The metric type. Use a `MetricType` enum value for standard types, or any
   * string for custom derived metrics produced by enrichment processes
   * (e.g. `'speed'`, `'pace'`, `'rep-rate'`, `'power'`).
   */
  readonly type: MetricType | string;
  /** Backward-compatible alias for type */
  readonly metricType?: MetricType | string;
  readonly origin: MetricOrigin;
  readonly unit?: string;

  /**
   * Visibility instruction. The only live value is `'suppress'`, which hides
   * all metrics of this type from display (resolved by the ownership ledger).
   * Most metrics carry no action (undefined = passive).
   */
  readonly action?: MetricAction;

  /**
   * Block key that created/owns this metric.
   * Present for runtime and user-collected metrics.
   */
  readonly sourceBlockKey?: string;

  /**
   * Timestamp when this metric was created/recorded.
   * Present for runtime and user-collected metrics.
   */
  readonly timestamp?: Date;

  /**
   * Processor-attached structured payload. Summary processors (e.g. TIS) hang
   * derivation metadata (effortSlug, effortDiscipline, effortIntensityTier,
   * component scores) on the projection value metric; fact normalization reads
   * it back out. Pure data — survives the stored-logs round-trip.
   */
  readonly metadata?: Record<string, unknown>;

  /** Optional explicit ownership layer for legacy compatibility */
  readonly ownershipLayer?: MetricOwnershipLayer;

  /** Optional human-readable name or label */
  readonly name?: string;

  /**
   * Optional icon (emoji/glyph) for hint metrics. Hints without an icon are
   * data-only — they never render in display surfaces; a hint WITH an icon
   * renders as the icon alone, with the hint text on hover.
   */
  readonly icon?: string;
}

/**
 * Metric type enumeration.
 *
 * Time-related terms follow the glossary in docs/architecture/time-terminology.md:
 * - **Duration** (Parser)  — planned target from the script (e.g., "5:00" -> 300 000 ms)
 * - **Time / Spans** (Block) — the raw TimeSpan[] start/stop recordings a block tracks
 * - **TimeStamp** (Runtime) — system Date.now() when a message is logged
 * - **Elapsed** (Runtime)  — Σ(end - start) of each span segment (active time, excludes pauses)
 * - **Total** (Runtime)    — lastEnd - firstStart (wall-clock bracket, includes pauses)
 */
export enum MetricType {
  /**
   * **Duration** (Core) — parser-defined planned target.
   *
   * A metric defined by the CodeStatement during parsing (e.g., "5:00" -> 300 000 ms).
   * It can be a time (duration) or a placeholder to be resolved.
   * Owned by the parser — the runtime reads it but never computes it.
   */
  Duration = 'duration',

  /**
   * **Spans** (Core) — raw start/stop TimeSpan[] recordings.
   *
   * Source-of-truth data recorded using the runtime clock.
   * Each span represents a continuous period of active (unpaused) execution.
   * These can be recorded at runtime or back-filled during analytics.
   */
  Spans = 'spans',

  /**
   * **SystemTime** (Core) — real system time (Date.now()) when a message is logged.
   *
   * Ground-truth wall-clock reference (timestamp) associated with system time metrics.
   * Independent of the runtime clock.
   */
  SystemTime = 'system-time',

  /** Live timer state written into block memory by the count-up/count-down timer behaviors. */
  Time = 'time',

  /** Active elapsed time — Σ(end - start) of active spans; derived during analytics. */
  Elapsed = 'elapsed',

  /** Total wall-clock bracket (lastEnd - firstStart) for a block; derived during analytics. */
  Total = 'total',

  Rep = 'rep',
  Effort = 'effort',
  /**
   * **Equipment** (Core) — ordered deduplicated canonical equipment slugs for a
   * statement (e.g. `["dumbbell"]` from `10 Dumbbell Snatch`). One metric per
   * statement; `metadata.refs` carries structured ReferenceRef entries,
   * `metadata.source` the authored label, `metadata.diagnostics` any
   * unknown/ambiguous/malformed reference findings.
   */
  Equipment = 'equipment',
  Distance = 'distance',
  Rounds = 'rounds',
  CurrentRound = 'current-round',
  Action = 'action',
  Increment = 'increment',
  Group = 'group',
  Text = 'text',
  Resistance = 'resistance',
  Sound = 'sound',
  System = 'system',
  Label = 'label',
  Lap = 'lap',
  Metric = 'metric',

  /**
   * **Hint** (Core) — a semantic marker emitted by a dialect or the parser.
   *
   * Dot-namespaced string markers (e.g. `workout.amrap`, `behavior.required_timer`)
   * that strategies and the label composer query to drive compilation decisions.
   * Hints are metrics so they flow through the single ownership channel, but they
   * are excluded from display resolution and from runtime block fragments.
   */
  Hint = 'hint',

  /** Generic custom metric bucket for parser-owned property metrics. */
  Custom = 'custom',
  Volume = 'volume',
  Intensity = 'intensity',

  /** Climb grade label carried by an observation (e.g. `V8`, `5.12a`) —
   *  user-authored grade metrics promote to the analytics `grade` dim. */
  Grade = 'grade',
  Load = 'load',
  Work = 'work',

  /** Per-set Reps in Reserve (real-time, strength) */
  RIR = 'rir',

  /** Post-session subjective effort rating (0–10) */
  SessionRPE = 'session-rpe',

  /** Session RPE x total minutes */
  SessionLoad = 'session-load',

  /** Normalized MET ((Activity METs ÷ METmax) x 100) */
  METScore = 'met-score',

  /** Training Intensity Score (composite) */
  TIS = 'tis',

  /** Runtime-layer calculated metric emitted from declarative formulas */
  Calculated = 'calculated',

  /** Skipped-Dependency Diagnostic emitted by the Metric Shake-Out Queue */
  Diagnostic = 'diagnostic',
  /**
   * **Choice** (Parser) — a pipe-separated OR expression.
   *
   * Emitted by Fusion when a pipe separates two homogeneous alternatives
   * (same MetricType on both sides). Carries `alternatives: IMetric[]`.
   * Resolved in the Pre-Run Wizard before the JIT compiles: the chosen
   * alternative is written at origin `user-plan` into the Statement's
   * MetricContainer, shadowing this group via ownership-layer precedence.
   * Never reaches compiled Blocks or display output once resolved.
   */
  Choice = 'choice',
}

/**
 * Concrete helper class implementing IMetric
 */
export class Metric implements IMetric {
  readonly type: MetricType | string;
  readonly metricType?: MetricType | string;
  readonly value?: unknown;
  readonly origin: MetricOrigin;
  readonly unit?: string;
  readonly action?: MetricAction;
  readonly image?: string;
  readonly sourceBlockKey?: string;
  readonly timestamp?: Date;
  readonly metadata?: Record<string, unknown>;
  readonly name?: string;
  readonly ownershipLayer?: MetricOwnershipLayer;

  constructor(
    typeOrName: MetricType | string,
    valueOrType?: unknown,
    originOrValue?: unknown,
    unit?: string,
    origin?: MetricOrigin | string,
    action?: MetricAction | string,
    image?: string,
  ) {
    if (
      typeof valueOrType === 'string' &&
      (typeof originOrValue === 'number' ||
        typeof originOrValue === 'string' ||
        typeof originOrValue === 'boolean' ||
        originOrValue === null ||
        originOrValue === undefined)
    ) {
      // Signature: (name, type, value, unit?, origin?, action?, image?)
      this.name = String(typeOrName);
      this.type = valueOrType;
      this.metricType = valueOrType;
      this.value = originOrValue;
      this.unit = unit;
      this.origin = (origin as MetricOrigin) || 'parser';
      this.action = action === 'suppress' ? 'suppress' : undefined;
      this.image = image ?? String(originOrValue ?? valueOrType);
    } else {
      // Signature: (type, value?, origin?, unit?, action?, image?)
      this.type = typeOrName;
      this.metricType = typeOrName;
      this.value = valueOrType;
      this.origin = (originOrValue as MetricOrigin) || 'parser';
      this.unit = unit;
      this.action = (typeof origin === 'string' && origin === 'suppress')
        ? 'suppress'
        : (action === 'suppress' ? 'suppress' : undefined);
      this.image = image ?? String(valueOrType ?? typeOrName);
    }
  }

  toNumber(): number {
    if (typeof this.value === 'number') return this.value;
    if (typeof this.value === 'string') {
      const parsed = parseFloat(this.value);
      return isNaN(parsed) ? 0 : parsed;
    }
    return 0;
  }
}
